import Foundation

/// Tiny runtime-switchable localization. Add a language by adding a table with the same keys;
/// `--check-strings` fails the build when a key is missing.
enum Lang: String { case tr, en }

enum L10n {
    nonisolated(unsafe) static var lang: Lang = .en

    static func string(_ key: String) -> String {
        table[lang]?[key] ?? table[.en]?[key] ?? key
    }

    static func phrases(_ key: String) -> [String] {
        lines[lang]?[key] ?? lines[.en]?[key] ?? []
    }

    static func check() -> Bool {
        var ok = true
        let en = Set(table[.en]!.keys), tr = Set(table[.tr]!.keys)
        for k in en.symmetricDifference(tr).sorted() { print("missing string: \(k)"); ok = false }
        let le = Set(lines[.en]!.keys), lt = Set(lines[.tr]!.keys)
        for k in le.symmetricDifference(lt).sorted() { print("missing phrase list: \(k)"); ok = false }
        print(ok ? "strings ok (\(en.count) keys, \(le.count) phrase lists)" : "strings FAILED")
        return ok
    }

    static let table: [Lang: [String: String]] = [.tr: tr, .en: en]
    static let lines: [Lang: [String: [String]]] = [.tr: trLines, .en: enLines]

